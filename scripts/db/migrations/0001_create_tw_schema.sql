-- 역할-권한 부여.
--
-- 근거는 DESIGN_admin_screen_inventory_v0_1.md §5 화면-권한 매트릭스다(사용자
-- 확인 2026-08-06). 매트릭스는 **누적이 아니다** — 상위 역할이 하위 역할의
-- 쓰기 권한을 자동으로 갖지 않는다. 특히 ADMIN 에게 command:approve 를 주지
-- 않는다. 주면 계정 관리자가 자기 신청을 승인할 수 있어 §17.3 4-eyes 가
-- 무너진다.
--
-- artifact:read 는 A-08(아티팩트 열람 정책) 미승인이므로 어떤 역할에도
-- 부여하지 않는다. 매트릭스의 '○' 표기가 그 뜻이다.
--
-- command:resync 는 설계에 대응 화면이 없어 부여 대상이 불명확하다.
-- 현재 어떤 역할에도 부여하지 않는다. OPEN QUESTION 으로 보고한다.

INSERT INTO TW_ROLE_PERMISSION (role_cd, perm_cd)
SELECT r.role_cd, p.perm_cd
  FROM (VALUES
        ('VIEWER'), ('OPERATOR'), ('POLICY_MANAGER'),
        ('APPROVER'), ('ADMIN'), ('AUDITOR')
       ) AS r(role_cd)
  CROSS JOIN (VALUES
        ('target:read'), ('target:history:read'),
        ('batch:read'), ('policy:read')
       ) AS p(perm_cd);

