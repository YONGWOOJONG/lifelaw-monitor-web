CREATE TABLE TW_APPROVAL (
    approval_id        BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    command_id         BIGINT         NOT NULL,
    risk_level_cd      VARCHAR(10)    NOT NULL,
    requested_by       VARCHAR(100)   NOT NULL,
    approver           VARCHAR(100)   NOT NULL,
    decision_cd        VARCHAR(20)    NOT NULL,
    decision_reason    VARCHAR(1000)  NOT NULL,
    reauth_verified_yn CHAR(1)        NOT NULL DEFAULT 'N',
    decided_at         TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
    CONSTRAINT pk_tw_approval PRIMARY KEY (approval_id),
    CONSTRAINT fk_tw_approval_command FOREIGN KEY (command_id)
        REFERENCES TW_ADMIN_COMMAND (command_id),
    CONSTRAINT ck_tw_approval_risk CHECK (risk_level_cd IN (
        'LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_tw_approval_decision CHECK (decision_cd IN (
        'APPROVED', 'REJECTED')),
    CONSTRAINT ck_tw_approval_reauth_yn CHECK (reauth_verified_yn IN ('Y', 'N')),
    CONSTRAINT ck_tw_approval_reason CHECK (btrim(decision_reason) <> ''),
    -- 4-eyes 를 DB 에서 강제한다.
    CONSTRAINT ck_tw_approval_four_eyes CHECK (approver <> requested_by),
    -- CRITICAL 승인은 재인증 없이 성립할 수 없다(설계 §18 최고 등급).
    CONSTRAINT ck_tw_approval_critical_reauth CHECK (
        risk_level_cd <> 'CRITICAL'
        OR decision_cd = 'REJECTED'
        OR reauth_verified_yn = 'Y')
);

CREATE INDEX ix_tw_approval_command ON TW_APPROVAL (command_id);

COMMENT ON TABLE TW_APPROVAL IS '승인 원장. append-only. 결정을 수정하지 않고 새 행을 남긴다';
COMMENT ON COLUMN TW_APPROVAL.risk_level_cd IS
  '설계 §18 위험 등급. LOW 저 / MEDIUM 중 / HIGH 고 / CRITICAL 최고';
COMMENT ON COLUMN TW_APPROVAL.reauth_verified_yn IS
  '재인증 확인 여부. CRITICAL 승인에는 Y 가 강제된다';

-- ---------------------------------------------------------------------------
-- 감사 로그 (설계 §19.1) — append-only
