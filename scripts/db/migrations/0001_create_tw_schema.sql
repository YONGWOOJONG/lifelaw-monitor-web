CREATE TABLE TW_SESSION (
    session_token_hash  CHAR(64)       NOT NULL,
    user_id             BIGINT         NOT NULL,
    csrf_token_hash     CHAR(64)       NOT NULL,
    source_ip           VARCHAR(45),
    user_agent          VARCHAR(500),
    created_at          TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
    last_seen_at        TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
    absolute_expires_at TIMESTAMPTZ(3) NOT NULL,
    reauth_at           TIMESTAMPTZ(3),
    CONSTRAINT pk_tw_session PRIMARY KEY (session_token_hash),
    CONSTRAINT fk_tw_session_user FOREIGN KEY (user_id)
        REFERENCES TW_USER (user_id),
    CONSTRAINT ck_tw_session_expiry CHECK (absolute_expires_at > created_at)
);

CREATE INDEX ix_tw_session_user ON TW_SESSION (user_id);
CREATE INDEX ix_tw_session_expiry ON TW_SESSION (absolute_expires_at);

COMMENT ON TABLE TW_SESSION IS '서버 측 세션. 로그아웃·권한 변경 시 행을 삭제해 즉시 무효화한다';
COMMENT ON COLUMN TW_SESSION.session_token_hash IS
  '세션 토큰의 SHA-256. 원본 토큰을 저장하지 않는다. DB 유출만으로 세션을 탈취할 수 없게 한다';
COMMENT ON COLUMN TW_SESSION.last_seen_at IS '유휴 만료 계산 기준. 요청마다 갱신되는 유일한 컬럼';
COMMENT ON COLUMN TW_SESSION.reauth_at IS '재인증 완료 시각. 최고 위험 작업은 이 값의 신선도를 검사한다';

-- ---------------------------------------------------------------------------
-- 관리 명령 Inbox (설계 §9)
-- ---------------------------------------------------------------------------

CREATE TABLE TW_ADMIN_COMMAND (
    command_id       BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    command_type     VARCHAR(30)    NOT NULL,
    payload          JSONB          NOT NULL,
    idempotency_key  VARCHAR(200)   NOT NULL,
    requested_by     VARCHAR(100)   NOT NULL,
    requested_reason VARCHAR(1000)  NOT NULL,
    approved_by      VARCHAR(100),
    status           VARCHAR(20)    NOT NULL DEFAULT 'PENDING',
    expires_at       TIMESTAMPTZ(3) NOT NULL,
    result_msg       VARCHAR(1000),
    reg_dt           TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
    mod_dt           TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
    CONSTRAINT pk_tw_admin_command PRIMARY KEY (command_id),
    CONSTRAINT uk_tw_admin_command_idem UNIQUE (idempotency_key),
    CONSTRAINT ck_tw_admin_command_type CHECK (command_type IN (
        'RERUN_BATCH', 'CANCEL_BATCH', 'RESET_TARGET', 'RESYNC_R_MASTER')),
    CONSTRAINT ck_tw_admin_command_status CHECK (status IN (
        'PENDING', 'ACCEPTED', 'REJECTED', 'IN_PROGRESS',
        'DONE', 'FAILED', 'EXPIRED')),
    CONSTRAINT ck_tw_admin_command_reason CHECK (btrim(requested_reason) <> ''),
    CONSTRAINT ck_tw_admin_command_expiry CHECK (expires_at > reg_dt),
    -- payload 는 객체여야 한다. 배열·스칼라 유입을 막는다.
    CONSTRAINT ck_tw_admin_command_payload CHECK (jsonb_typeof(payload) = 'object'),
    -- 4-eyes: 신청자와 승인자는 같을 수 없다. 애플리케이션 검사에 의존하지 않는다.
    CONSTRAINT ck_tw_admin_command_four_eyes CHECK (
        approved_by IS NULL OR approved_by <> requested_by)
);

CREATE INDEX ix_tw_admin_command_status ON TW_ADMIN_COMMAND (status, expires_at);
CREATE INDEX ix_tw_admin_command_type ON TW_ADMIN_COMMAND (command_type, status);

COMMENT ON TABLE TW_ADMIN_COMMAND IS
  '관리 명령 Inbox. Web 은 PENDING 행을 INSERT 만 하고, 이후 상태 전이는 소비자(수집기)가 수행한다';
COMMENT ON COLUMN TW_ADMIN_COMMAND.idempotency_key IS
  '중복 제출 차단. UNIQUE 제약으로 강제하며 애플리케이션 체크에 의존하지 않는다';
COMMENT ON COLUMN TW_ADMIN_COMMAND.expires_at IS
  '만료 시각. 어제 신청한 RERUN_BATCH 가 오늘 실행되는 것을 막는다';
COMMENT ON COLUMN TW_ADMIN_COMMAND.status IS
  'PENDING 은 "대기 중"이 아니라 "미처리"다. 소비자 미구현 상태에서는 영구히 PENDING 에 남는다';

-- ---------------------------------------------------------------------------
-- 승인 원장 (설계 §18)
