CREATE TABLE TW_USER (
    user_id          BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    login_id         VARCHAR(100)   NOT NULL,
    user_nm          VARCHAR(100)   NOT NULL,
    password_hash    VARCHAR(255)   NOT NULL,
    use_yn           CHAR(1)        NOT NULL DEFAULT 'Y',
    pwd_changed_at   TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
    last_login_at    TIMESTAMPTZ(3),
    failed_login_cnt INTEGER        NOT NULL DEFAULT 0,
    locked_until     TIMESTAMPTZ(3),
    reger            VARCHAR(100)   NOT NULL,
    reg_dt           TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
    moder            VARCHAR(100)   NOT NULL,
    mod_dt           TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
    CONSTRAINT pk_tw_user PRIMARY KEY (user_id),
    CONSTRAINT uk_tw_user_login UNIQUE (login_id),
    CONSTRAINT ck_tw_user_use_yn CHECK (use_yn IN ('Y', 'N')),
    CONSTRAINT ck_tw_user_failed_cnt CHECK (failed_login_cnt >= 0),
    -- 평문·짧은 해시 유입 방지. Argon2id 인코딩 문자열만 허용한다.
    CONSTRAINT ck_tw_user_pwd_argon2 CHECK (password_hash LIKE '$argon2id$%')
);

COMMENT ON TABLE TW_USER IS '관리자 계정. 삭제하지 않고 use_yn=N 으로 비활성화한다';
COMMENT ON COLUMN TW_USER.password_hash IS 'Argon2id 인코딩 해시. 평문·가역 암호 저장 금지';
COMMENT ON COLUMN TW_USER.failed_login_cnt IS '연속 로그인 실패 횟수. 성공 시 0으로 초기화';
COMMENT ON COLUMN TW_USER.locked_until IS '무차별 대입 방어 잠금 해제 시각';

