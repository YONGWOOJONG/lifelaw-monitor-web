CREATE TABLE TW_AUDIT_LOG (
    audit_id        BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    occurred_at     TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
    actor           VARCHAR(100)   NOT NULL,
    actor_role_cd   VARCHAR(30),
    source_ip       VARCHAR(45),
    user_agent      VARCHAR(500),
    action          VARCHAR(100)   NOT NULL,
    target_type     VARCHAR(50),
    target_id       VARCHAR(100),
    before_value    JSONB,
    after_value     JSONB,
    reason          VARCHAR(1000),
    approval_id     BIGINT,
    idempotency_key VARCHAR(200),
    result_cd       VARCHAR(20)    NOT NULL,
    CONSTRAINT pk_tw_audit_log PRIMARY KEY (audit_id),
    CONSTRAINT ck_tw_audit_log_result CHECK (result_cd IN (
        'SUCCESS', 'DENIED', 'FAILED', 'TIMEOUT'))
);

CREATE INDEX ix_tw_audit_log_occurred ON TW_AUDIT_LOG (occurred_at);
CREATE INDEX ix_tw_audit_log_actor ON TW_AUDIT_LOG (actor, occurred_at);
CREATE INDEX ix_tw_audit_log_target ON TW_AUDIT_LOG (target_type, target_id);

COMMENT ON TABLE TW_AUDIT_LOG IS
  'append-only 감사 로그. 런타임 롤에 UPDATE/DELETE 를 부여하지 않는다. 애플리케이션 규율만으로는 부족하다';
COMMENT ON COLUMN TW_AUDIT_LOG.result_cd IS
  '실패한 시도도 기록한다. DENIED 권한 거부 / TIMEOUT 배리어 경합';
COMMENT ON COLUMN TW_AUDIT_LOG.before_value IS '변경 전 값. 비밀번호·토큰·DSN 은 마스킹해 저장한다';
COMMENT ON COLUMN TW_AUDIT_LOG.after_value IS '변경 후 값. 비밀번호·토큰·DSN 은 마스킹해 저장한다';

-- approval_id 는 FK 를 걸지 않는다. 감사 로그는 승인 원장보다 오래 남아야 하고,
-- 승인 없이 발생한 사건(권한 거부 등)도 기록하기 때문이다.

COMMIT;
